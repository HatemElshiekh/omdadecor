/**
 * Seed generator (PLAN.md Section 20, "Seed assumptions").
 *
 *   npx tsx supabase/seed/seed.ts            -> writes supabase/seed/seed.sql
 *   psql "$SUPABASE_DB_URL" -f supabase/seed/seed.sql
 *
 * Idempotent: product ids are UUIDv5 of edara_row_no, every insert is an upsert.
 * Staff are NOT seeded here: they need PIN_PEPPER + auth users (Phase 3, pin-login).
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalize } from '../../src/lib/normalize.ts';
import { typeTerms } from '../../src/lib/synonyms.ts';
import { unitDefaults } from '../../src/lib/unitDefaults.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = <T>(p: string): T => JSON.parse(readFileSync(join(root, p), 'utf8')) as T;

interface Template {
  label: string;
  calc_mode: string | null;
  size_material_colors: string[];
  use_yes: string[];
  use_no: string[];
  say_to_customer: string[];
  install_and_complements: string[];
}
interface DemoProduct {
  edara_row_no: number;
  name: string;
  category: string;
  spec_type: string;
  stock_by_warehouse: Record<string, number>;
  facts_from_name: Record<string, string>;
  price: number | null;
  engineer_price: number | null;
  specs_status: 'draft_general_by_type' | 'approved';
}

export const WAREHOUSES: Array<[string, string]> = [
  ['nemis_main', 'فرع النميس الرئيسي'],
  ['nemis_shop', 'محل النميس'],
  ['asyut_new', 'مخزن أسيوط الجديدة'],
  ['moalemin', 'مخزن المعلمين'],
  ['car_direct', 'سيارة بيع مباشر'],
];

// RFC 4122 v5 (SHA-1, name-based) so re-seeding keeps the same ids.
const NS = '6f2b0d1e-8c1a-4f7e-9d3b-0a5c2e7f9b41';
export function uuidv5(name: string, ns = NS): string {
  const nsBytes = Buffer.from(ns.replace(/-/g, ''), 'hex');
  const h = createHash('sha1').update(nsBytes).update(name, 'utf8').digest();
  h[6] = (h[6]! & 0x0f) | 0x50;
  h[8] = (h[8]! & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString('hex');
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

// Single-quoted SQL literal for a JSON payload.
const jsonLit = (v: unknown): string => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;

/** Rows exactly as seeded (also used as test fixtures). */
export function buildRows() {
  const templates = read<Record<string, Template>>('data/spec_templates_by_type.json');
  const products = read<DemoProduct[]>('data/demo_products_100.json');

  const warehouses = WAREHOUSES.map(([id, name_ar]) => ({ id, name_ar }));
  const specTemplates = Object.entries(templates).map(([type, t]) => ({
    type,
    label_ar: t.label,
    calc_mode: t.calc_mode,
    size_material_colors: t.size_material_colors,
    use_yes: t.use_yes,
    use_no: t.use_no,
    say_to_customer: t.say_to_customer,
    install_and_complements: t.install_and_complements,
  }));
  const productRows = products.map((p) => {
    const t = templates[p.spec_type];
    if (!t) throw new Error(`Unknown spec_type ${p.spec_type} (row ${p.edara_row_no})`);
    return {
      id: uuidv5(`edara-row:${p.edara_row_no}`),
      edara_row_no: p.edara_row_no,
      name: p.name,
      category_ar: p.category,
      spec_type: p.spec_type,
      search_text: normalize(
        [p.name, p.category, t.label, typeTerms(p.spec_type)].filter(Boolean).join(' '),
      ),
      price: p.price,
      engineer_price: p.engineer_price,
      calc_mode: t.calc_mode,
      facts: p.facts_from_name,
      ...unitDefaults(p.spec_type, p.name, p.facts_from_name),
      specs_status: p.specs_status,
      stock: Object.fromEntries(WAREHOUSES.map(([wh]) => [wh, p.stock_by_warehouse[wh] ?? 0])),
    };
  });
  return { warehouses, specTemplates, productRows };
}

export function buildSeedSql(): string {
  const { warehouses, specTemplates, productRows } = buildRows();

  return `-- Generated by supabase/seed/seed.ts. Do not edit by hand.
begin;

insert into public.warehouses (id, name_ar)
select id, name_ar from jsonb_to_recordset(${jsonLit(warehouses)}) as x(id text, name_ar text)
on conflict (id) do update set name_ar = excluded.name_ar;

insert into public.spec_templates (type, label_ar, calc_mode, size_material_colors, use_yes, use_no, say_to_customer, install_and_complements)
select type, label_ar, calc_mode, size_material_colors, use_yes, use_no, say_to_customer, install_and_complements
from jsonb_populate_recordset(null::public.spec_templates, ${jsonLit(specTemplates)})
on conflict (type) do update set label_ar = excluded.label_ar, calc_mode = excluded.calc_mode,
  size_material_colors = excluded.size_material_colors, use_yes = excluded.use_yes, use_no = excluded.use_no,
  say_to_customer = excluded.say_to_customer, install_and_complements = excluded.install_and_complements;

create temp table _seed_products on commit drop as
select * from jsonb_to_recordset(${jsonLit(productRows)}) as x(
  id uuid, edara_row_no int, name text, category_ar text, spec_type text, search_text text,
  price numeric, engineer_price numeric, calc_mode text, facts jsonb,
  unit_width_cm numeric, unit_length_cm numeric, box_area_m2 numeric, piece_length_m numeric,
  specs_status text, stock jsonb);

insert into public.products (id, edara_row_no, name, category_ar, spec_type, search_text, price, engineer_price, calc_mode, facts, unit_width_cm, unit_length_cm, box_area_m2, piece_length_m, specs_status)
select id, edara_row_no, name, category_ar, spec_type, search_text, price, engineer_price, calc_mode, facts, unit_width_cm, unit_length_cm, box_area_m2, piece_length_m, specs_status
from _seed_products
on conflict (id) do update set edara_row_no = excluded.edara_row_no, name = excluded.name,
  category_ar = excluded.category_ar, spec_type = excluded.spec_type, search_text = excluded.search_text,
  price = excluded.price, engineer_price = excluded.engineer_price, calc_mode = excluded.calc_mode,
  facts = excluded.facts, unit_width_cm = excluded.unit_width_cm, unit_length_cm = excluded.unit_length_cm,
  box_area_m2 = excluded.box_area_m2, piece_length_m = excluded.piece_length_m;

insert into public.stock (product_id, warehouse_id, qty)
select p.id, s.key, s.value::numeric from _seed_products p, jsonb_each_text(p.stock) s
on conflict (product_id, warehouse_id) do update set qty = excluded.qty;

commit;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const target = join(root, 'supabase', 'seed', 'seed.sql');
  writeFileSync(target, buildSeedSql());
  console.log(`wrote ${target}`);
}
